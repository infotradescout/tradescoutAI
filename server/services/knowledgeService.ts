function findRepoRoot(startDir: string): string | null {
  // Walk up until we find package.json. This avoids brittle __dirname-relative paths
  // that break once compiled to dist/ in production.
  let current = path.resolve(startDir);
  for (let i = 0; i < 10; i++) {
    const pkg = path.join(current, "package.json");
    if (fs.existsSync(pkg)) return current;
    const parent = path.dirname(current);
    if (parent === current) break;
    current = parent;
  }
  return null;
}

function resolveRepoRoot(): string {
  return (
    findRepoRoot(process.cwd()) ??
    findRepoRoot(__dirname) ??
    // Last resort: keep behavior close to prior layout.
    path.resolve(__dirname, "..", "..")
  );
}

