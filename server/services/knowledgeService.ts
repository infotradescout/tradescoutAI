export function shouldUseInternetFallback(input: InternetFallbackDecisionInput): boolean {
  const { message, mode, sources, meta, hasManualOverride } = input;

  if (hasManualOverride) return false;
  if (mode !== "kb_site_then_web") return false;

  const lower = message.toLowerCase();
  // Codes, permits, inspections, zoning, and tax rules are authority- and
  // freshness-sensitive. A matching internal guide is useful context, but it
  // is not enough by itself to claim the current rule for a jurisdiction.
  if (isCodeOrPermitQuery(lower) || isTaxQuery(lower)) return true;

  const isExternalDiscoveryQuery =
    /\b(find|looking for|near me|best|compare|review|quote|estimate|price|cost|contractor|roofer|plumber|electrician|hvac|handyman|service)\b/.test(
      lower
    );

  if (!isExternalDiscoveryQuery) {
    return false;
  }

  const hasWebsiteData = sources.some((source) => {
    const title = typeof source === "string" ? source : source.title;
    return title.startsWith("TradeScout Cache") || title.startsWith("TradeScout Database");
  });
  const localSupplyCount = Math.max(
    meta?.contractors?.count ?? 0,
    meta?.communityPosts?.count ?? 0
  );
  const hasHealthyLocalSupply = localSupplyCount >= 3;

  const hasOnlyKnowledgeDocs =
    sources.length > 0 &&
    sources.every((source) => {
      const title = typeof source === "string" ? source : source.title;
      return (
        title === "TradeScout Brain (data folder)" ||
        title.startsWith("Admin ") ||
        title.startsWith("Admin County Override")
      );
    });

  if (hasOnlyKnowledgeDocs) {
    return true;
  }

  return !hasWebsiteData || !hasHealthyLocalSupply;
}

/**
 * Read a cached JSON file
 */
function readCacheFile(filename: string, isManual = false): any | null {
  try {
    const dir = isManual ? MANUAL_CACHE_DIR : AUTO_CACHE_DIR;
    const filepath = path.join(dir, filename);

    if (!fs.existsSync(filepath)) {
      return null;
    }

    const content = fs.readFileSync(filepath, "utf-8");
    return JSON.parse(content);
  } catch (error) {
    console.error(`Error reading cache ${filename}:`, error);
    return null;
  }
}

function walkKnowledgeFiles(dir: string): string[] {
  const files: string[] = [];
  if (!fs.existsSync(dir)) return files;

  const entries = fs.readdirSync(dir, { withFileTypes: true });
  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...walkKnowledgeFiles(fullPath));
    } else if (KNOWLEDGE_EXTENSIONS.has(path.extname(entry.name).toLowerCase())) {
      files.push(fullPath);
    }
  }
  return files;
}

async function loadKnowledgeText(filePath: string): Promise<string | null> {
  try {
    const stats = fs.statSync(filePath);
    const cached = knowledgeTextCache[filePath];
    if (cached && cached.mtimeMs === stats.mtimeMs) {
      return cached.text;
    }

    const ext = path.extname(filePath).toLowerCase();
    let text: string | null = null;

    if (ext === ".docx") {
      const result = await mammoth.extractRawText({ path: filePath });
      text = result.value;
    } else {
      text = fs.readFileSync(filePath, "utf-8");
    }

    const clean = text?.trim();
    if (clean) {
      knowledgeTextCache[filePath] = { mtimeMs: stats.mtimeMs, text: clean };
      return clean;
    }
  } catch (error) {
    console.error(`Error loading knowledge file ${filePath}:`, error);
  }

  return null;
}

function buildSnippet(text: string, terms: string[]): string {
  const lower = text.toLowerCase();
  const term = terms.find((t) => lower.includes(t));
  if (!term) {
    return text.slice(0, 600);
  }

  const idx = lower.indexOf(term);
  const start = Math.max(0, idx - 200);
  const end = Math.min(text.length, idx + 800);
  return text.slice(start, end);
}

async function searchLocalKnowledgeBase(
  message: string,
  countyCode?: string,
  stateCode?: string
): Promise<CacheResult> {
  if (!GENERATED_SCOUT_CORPUS_RETRIEVAL_ENABLED) {
    return { source: "none", data: null, layer: 0 };
  }

  try {
    const strictJurisdiction = isCodeOrPermitQuery(message.toLowerCase());
    const locality = {
      countyFips: /^\d{5}$/.test(String(countyCode || "").trim())
        ? String(countyCode).trim()
        : null,
      state: /^[a-z]{2}$/i.test(String(stateCode || "").trim())
        ? String(stateCode).trim().toUpperCase()
        : null,
    };
    const hybridQuery = {
      text: message,
      kind: "knowledge" as const,
      locality,
      strictLocality: strictJurisdiction && Boolean(locality.countyFips || locality.state),
      requireCountyMatch: strictJurisdiction && Boolean(locality.countyFips),
      limit: 10,
    };
    const cutoverResults = await searchScoutHybridCutover({ query: hybridQuery });
    if (cutoverResults?.length) {
      return {
        source: "manual",
        data: cutoverResults.slice(0, 3).map((result) => ({
          file: result.title,
          snippet: result.snippet,
          score: result.score,
          sourceUrl: result.sourceUrl,
          sourceId: result.id,
        })),
        itemCount: Math.min(3, cutoverResults.length),
        layer: 1,
      };
    }

    const existingRoots = KNOWLEDGE_ROOT_DIRS.filter((dir) => {
      try {
        return fs.existsSync(dir);
      } catch {
        return false;
      }
    });

    if (!existingRoots.length) {
      return { source: "none", data: null, layer: 0 };
    }

    const filesByRoot: Array<{ root: string; file: string }> = [];
    for (const root of existingRoots) {
      const files = walkKnowledgeFiles(root);
      for (const file of files) {
        filesByRoot.push({ root, file });
      }
    }

    if (!filesByRoot.length) {
      return { source: "none", data: null, layer: 0 };
    }

    const terms = message
      .toLowerCase()
      .split(/\s+/)
      .map((t) => t.trim())
      .filter((t) => t.length > 3);

    const matches: Array<{ file: string; snippet: string; score: number }> = [];

    for (const item of filesByRoot) {
      const text = await loadKnowledgeText(item.file);
      if (!text) continue;

      const lower = text.toLowerCase();
      let score = 0;
      for (const term of terms) {
        if (lower.includes(term)) {
          score += 1;
        }
      }

      if (score > 0) {
        const rootLabel = path.basename(item.root);
        matches.push({
          file: `[${rootLabel}] ${path.relative(item.root, item.file)}`,
          snippet: buildSnippet(text, terms),
          score,
        });
      }
    }

    matches.sort((a, b) => b.score - a.score);
    const top = matches.slice(0, 3);
    void observeScoutHybridShadow({
      query: hybridQuery,
      legacyIds: top.map((match) => match.file),
    });

    if (top.length) {
      return {
        source: "manual",
        data: top,
        itemCount: top.length,
        layer: 1,
      };
    }
  } catch (error) {
    console.error("Local knowledge search error:", error);
  }

  return { source: "none", data: null, layer: 0 };
}

function isCodeOrPermitQuery(lower: string): boolean {
  return /\b(code|building code|permit|permitting|inspection|inspector|zoning|setback|occupancy|egress|fire\s*safety|smoke\s*alarm|carbon\s*monoxide|electrical|panel|breaker|gfci|afci|receptacle|outlet|subpanel|service\s*entrance|plumbing|drain|sewer|cleanout|trap|vent|slope|foundation|slab|footing|framing|joist|beam|header|stair|handrail|guardrail|deck)\b/.test(
    lower
  );
}

function isTaxQuery(lower: string): boolean {
  return /\b(tax|property\s*tax|assessment|assessed\s*value|mill\s*rate|valuation|homestead|escrow|tax\s*lien|delinquent\s*tax|tax\s*sale|foreclosure)\b/.test(
    lower
  );
}

